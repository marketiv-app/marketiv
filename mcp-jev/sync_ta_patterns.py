#!/usr/bin/env python3
"""Copy the TA pattern NAMES from the Ava repo's resolver catalog (jobs/ta-tools/ta-signal-catalog.json — the single
source of truth, pinned to the screening engine by ta_scan::catalog_tests) into ta_patterns.json here, which builds
TaSignal.pattern's description in server.py. Committed (so what's live is in git); deploy.sh runs `--check` and refuses
to deploy a stale copy.  Usage: python3 sync_ta_patterns.py [--check]   (AVA_REPO overrides ~/Documents/Ava Advisor)"""
import json, os, sys, pathlib

HERE = pathlib.Path(__file__).resolve().parent
SRC = pathlib.Path(os.environ.get("AVA_REPO", os.path.expanduser("~/Documents/Ava Advisor"))) / "jobs/ta-tools/ta-signal-catalog.json"
DST = HERE / "ta_patterns.json"

rows = json.loads(SRC.read_text())["rows"]
def _frac_b(r):  # the pattern's catalog example puts a FRACTION in b (0.2 = 20%) → b is a magnitude, not a line/level
    try: return 0 < float((r.get("example") or {}).get("b", "x")) < 1
    except ValueError: return False
want = {"_comment": "GENERATED by sync_ta_patterns.py from Ava jobs/ta-tools/ta-signal-catalog.json — do not edit by hand.",
        "patterns": sorted(r["name"] for r in rows),
        "fraction_b": sorted(r["name"] for r in rows if _frac_b(r)),
        # the catalog example carries no operand at all → the pattern takes none (omit a/b)
        "operand_free": sorted(r["name"] for r in rows if not ({"a", "b"} & set((r.get("example") or {}).keys())))}
text = json.dumps(want, indent=1) + "\n"
if "--check" in sys.argv:
    have = DST.read_text() if DST.exists() else ""
    if have != text:
        sys.exit(f"✗ ta_patterns.json is stale vs {SRC} — run: python3 {pathlib.Path(__file__).name}")
    print("ta_patterns.json up to date ✓")
else:
    DST.write_text(text); print(f"wrote {DST.name}: {len(want['patterns'])} patterns")
